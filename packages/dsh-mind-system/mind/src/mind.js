/**
 * 注册心智索引分节。
 *
 * 只有在 `systemPrompt` 服务可用时才注册：纯 Node 环境（单测、冒烟）
 * 没有这个服务，缺它不该让整个插件装载失败 —— 这是"附加能力缺了要降级，
 * 不能拖垮核心"的直接应用。
 *
 * @param ctx 已具备 systemPrompt 服务的上下文。
 * @returns 注销函数；未注册时返回 undefined。
 */
export function registerMindSection(ctx) {
  const host = ctx;
  if (host?.systemPrompt === undefined) return undefined;
  return host.systemPrompt.section({
    name: SECTION_NAME,
    order: SECTION_ORDER,
    // 正文里有 `{{` 风格的可能性极低，但关掉插值更稳：
    // 这是常驻文本，任何意外的变量替换都只会让判断变形。
    interpolate: false,
    text: SECTION_TEXT,
  });
}
