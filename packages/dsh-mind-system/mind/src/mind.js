/**
 * 心智索引 —— 系统提示里的"判断顺序"，不是工具清单。
 *
 * ## 这一层在解决什么问题
 *
 * 每个插件都自己往系统提示里塞一段"什么时候该用我"。单看每一段都对，
 * 合起来就成了**并列的广告**：agent 面对一个真实问题，看到的是若干个
 * 各自声称适用的工具，而没有任何东西告诉它**先问哪个、什么时候别用**。
 *
 * 结果有两种典型形态，都在本机实测过：
 *
 * 1. 工具都在，但没人想起来用（`hinted=0` 持续两周无人察觉）
 * 2. 用了，但用错层（拿因果分析去做一次性的信息整理，输出模板空转）
 *
 * 缺的不是工具，是**选择工具的那个判断**。所以这里写的不是"有哪些工具"，
 * 而是"遇到什么信号时，该先问哪一类问题"——工具名只是判断的落点。
 *
 * ## 为什么不写成一个"超级工具"
 *
 * 一个"帮我选工具"的工具需要 agent 先意识到自己该选工具，这是同一层
 * 悖论。判断顺序必须**常驻**在它能读到的地方，且必须短 ——
 * 它每一轮都在付 token。
 *
 * ## 三条硬约束
 *
 * 1. **不重复工具说明**：参数与返回值在各自工具的 description 里，用到时
 *    才加载。这里只写"什么时候轮到它"。
 * 2. **给"不要用"的理由**：只说什么时候该用的索引，会诱使 agent 到处套用。
 *    每条都要能说出反例。
 * 3. **顺序要能被反驳**：每步都写"如果…就不是这类问题"，让它能自己
 *    跳出这个顺序，而不是被顺序绑死。
 */

/**
 * 系统提示分节名（全局唯一，重复注册会抛错）。
 *
 * 命名前缀用 `mind:` 而不是具体工具名 —— 它不属于任何一个插件的能力，
 * 而是横跨它们的判断层。
 */
export const SECTION_NAME = 'mind:orchestration';

/**
 * 分节位置。
 *
 * `TOOL_GOAL` 是 2400、`TOOL_WORKFLOW` 是 2600（见宿主
 * dsh-system-prompt 的 SECTION_ORDERS）。放在 2410：
 *
 * - 在目标之后：agent 得先知道要达成什么，才谈得上"用哪个手段"
 * - 在具体工具说明前：它是"目录"，目录该排在各章之前
 * - 在 clis 的 2450 之前：因果判断是**分支之一**，不是总纲
 *
 * 这不是装饰性排序：宿主按 order 升序拼接，读到这里的时刻正是
 * agent 刚确定目标、还没决定动作的那个空档。
 */
export const SECTION_ORDER = 2410;

